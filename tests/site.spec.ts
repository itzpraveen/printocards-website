test('reduced motion and unavailable WebGL retain a complete experience', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.addInitScript(() => { const original = HTMLCanvasElement.prototype.getContext; HTMLCanvasElement.prototype.getContext = function(type: string, ...args: unknown[]) { if (type === 'webgl' || type === 'webgl2') return null; return original.call(this, type as '2d', ...args) } as typeof HTMLCanvasElement.prototype.getContext })
  await page.goto('/')
  await expect(page.locator('.fallback-cards')).not.toHaveClass(/is-hidden/)
  await page.getByRole('button', { name: 'Flip card', exact: true }).click()
  await expect(page.locator('.front-card')).toHaveClass(/flipped/)
  await page.getByRole('link', { name: 'Find your perfect card' }).click()
  await expect(page.locator('.product-tile')).toHaveCount(32)
})

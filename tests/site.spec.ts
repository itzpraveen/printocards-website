import { test, expect } from '@playwright/test'

test('home is usable, responsive, and all audience tabs work', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Small cards. Big connections.' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Find your perfect card' })).toBeVisible()
  await page.getByRole('button', { name: 'Ink card colour', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Ink card colour', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Flip card', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Flip card', exact: true })).toHaveAttribute('aria-pressed', 'true')
  for (const label of ['For you', 'For your business', 'For your institution', 'For your customers']) {
    const tab = page.getByRole('tab', { name: new RegExp(`${label}$`) }); await tab.click(); await expect(tab).toHaveAttribute('aria-selected', 'true')
    await expect(page.getByRole('tabpanel')).toBeVisible()
  }
  await expect(page.getByRole('button', { name: 'How much will my order cost?' })).toBeVisible()
  await page.getByRole('button', { name: 'How much will my order cost?' }).click()
  await expect(page.getByText('Pricing depends on your product')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBeTruthy()
  expect(errors).toEqual([])
})

test('catalogue searches, combines filters and recovers from an empty result', async ({ page }) => {
  await page.goto('/products')
  await expect(page.locator('.product-tile')).toHaveCount(32)
  await page.getByRole('button', { name: 'Smart cards 5', exact: true }).click()
  await expect(page.locator('.product-tile')).toHaveCount(5)
  await page.getByLabel('Filter by customer type').selectOption('Individuals')
  await expect(page.locator('.product-tile')).toHaveCount(2)
  await page.getByRole('textbox', { name: 'Search products' }).fill('wooden')
  await expect(page.locator('.product-tile')).toHaveCount(1)
  await page.reload(); await expect(page.locator('.product-tile')).toHaveCount(1)
  await page.getByRole('textbox', { name: 'Search products' }).fill('does-not-exist')
  await expect(page.getByRole('heading', { name: 'No matches just yet.' })).toBeVisible()
  await page.getByRole('button', { name: 'Show all products' }).click()
  await expect(page.locator('.product-tile')).toHaveCount(32)
})

